/**
 * Lightweight, zero-dependency RFC4122 UUID v4 generator for React Native / Expo.
 * Avoids native crypto getRandomValues requirement that causes runtime crashes in React Native.
 */
export function generateUUID(): string {
  return 'xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx'.replace(/[xy]/g, (c) => {
    const r = (Math.random() * 16) | 0;
    const v = c === 'x' ? r : (r & 0x3) | 0x8;
    return v.toString(16);
  });
}
